import { DailySummary, StreakRecord, ThemeColorName } from '../types';
import { COLOR_PALETTES } from './lawnGraph';
import { generatePast53WeeksGrid, formatDateString } from '../utils/dateUtils';

export interface ShareCardOptions {
  summariesMap: Map<string, DailySummary>;
  streak: StreakRecord;
  totalScore: number;
  themeColor: ThemeColorName;
  darkMode: boolean;
  masking: boolean; // プライバシーマスキング
  period: 'year' | 'month'; // 年間または直近1ヶ月
  userName?: string;
}

/**
 * SNS共有用の高解像度カード画像 (1200x630px) を Canvas で生成してダウンロードする
 */
export async function exportShareCardImage(options: ShareCardOptions): Promise<string> {
  const { summariesMap, streak, totalScore, themeColor, darkMode, masking, period, userName } = options;

  const canvas = document.createElement('canvas');
  canvas.width = 1200;
  canvas.height = 630;
  const ctx = canvas.getContext('2d');
  if (!ctx) {
    throw new Error('Canvas context not available');
  }

  // 背景描画
  const bgColor = darkMode ? '#0d1117' : '#ffffff';
  ctx.fillStyle = bgColor;
  ctx.fillRect(0, 0, canvas.width, canvas.height);

  // 背景アクセント枠線
  ctx.strokeStyle = darkMode ? '#30363d' : '#e1e4e8';
  ctx.lineWidth = 4;
  ctx.strokeRect(16, 16, canvas.width - 32, canvas.height - 32);

  // ヘッダータイトル描画
  ctx.fillStyle = darkMode ? '#f0f6fc' : '#24292f';
  ctx.font = 'bold 36px sans-serif';
  const displayTitle = masking ? 'Creator Activity Lawn' : (userName ? `${userName} の活動記録` : 'v-activity-lawn');
  ctx.fillText(displayTitle, 60, 90);

  // サブテキスト
  ctx.font = '18px sans-serif';
  ctx.fillStyle = darkMode ? '#8b949e' : '#57606a';
  const periodLabel = period === 'year' ? '過去53週間の活動' : '直近4週間の活動';
  ctx.fillText(`${periodLabel} • Generated by v-activity-lawn`, 60, 125);

  // 統計情報バッジ描画
  const badgeY = 160;
  drawStatBadge(ctx, 60, badgeY, '年間総スコア', `${Math.round(totalScore)} pt`, darkMode);
  drawStatBadge(ctx, 280, badgeY, '現在の継続日数', `${streak.currentStreakDays} 日`, darkMode);
  drawStatBadge(ctx, 500, badgeY, '最長継続日数', `${streak.longestStreakDays} 日`, darkMode);

  // 草グラフの描画
  const weeksCount = period === 'year' ? 53 : 4;
  const allDates = generatePast53WeeksGrid(formatDateString(), 0);
  const dates = allDates.slice(-(weeksCount * 7));

  const palette = COLOR_PALETTES[themeColor] || COLOR_PALETTES.green;
  const colors = darkMode ? palette.dark : palette.light;

  const startX = 60;
  const startY = 270;
  // 週数に応じたセルサイズとギャップの調整
  const cellSize = period === 'year' ? 16 : 40;
  const cellGap = period === 'year' ? 4 : 8;
  const step = cellSize + cellGap;

  for (let i = 0; i < dates.length; i++) {
    const col = Math.floor(i / 7);
    const row = i % 7;
    const x = startX + col * step;
    const y = startY + row * step;

    const dateStr = dates[i];
    const summary = summariesMap.get(dateStr);
    const level = summary?.level ?? 0;
    const hasSpecial = summary?.hasSpecialMilestone ?? false;

    // 角丸セルの描画
    ctx.fillStyle = colors[level];
    drawRoundedRect(ctx, x, y, cellSize, cellSize, period === 'year' ? 3 : 6);
    ctx.fill();

    // 特別マイルストーン（動画・配信）枠線
    if (hasSpecial) {
      ctx.strokeStyle = '#f59e0b';
      ctx.lineWidth = period === 'year' ? 2 : 3;
      drawRoundedRect(ctx, x, y, cellSize, cellSize, period === 'year' ? 3 : 6);
      ctx.stroke();

      // ゴールドアクセントドット
      ctx.fillStyle = '#f59e0b';
      ctx.beginPath();
      ctx.arc(x + cellSize - (period === 'year' ? 3 : 6), y + (period === 'year' ? 3 : 6), period === 'year' ? 2 : 4, 0, Math.PI * 2);
      ctx.fill();
    } else {
      ctx.strokeStyle = darkMode ? '#30363d' : '#e1e4e8';
      ctx.lineWidth = 1;
      drawRoundedRect(ctx, x, y, cellSize, cellSize, period === 'year' ? 3 : 6);
      ctx.stroke();
    }
  }

  // フッター情報
  ctx.fillStyle = darkMode ? '#8b949e' : '#57606a';
  ctx.font = '16px sans-serif';
  ctx.fillText('v-activity-lawn | 完全ローカル・パッシブ検知のVTuber活動草拡張機能', 60, 580);

  // 画像データURLの生成と自動ダウンロード
  const dataUrl = canvas.toDataURL('image/png');
  const link = document.createElement('a');
  link.download = `v-activity-lawn-${formatDateString()}.png`;
  link.href = dataUrl;
  link.click();

  return dataUrl;
}

function drawRoundedRect(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  width: number,
  height: number,
  radius: number
) {
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.lineTo(x + width - radius, y);
  ctx.quadraticCurveTo(x + width, y, x + width, y + radius);
  ctx.lineTo(x + width, y + height - radius);
  ctx.quadraticCurveTo(x + width, y + height, x + width - radius, y + height);
  ctx.lineTo(x + radius, y + height);
  ctx.quadraticCurveTo(x, y + height, x, y + height - radius);
  ctx.lineTo(x, y + radius);
  ctx.quadraticCurveTo(x, y, x + radius, y);
  ctx.closePath();
}

function drawStatBadge(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  label: string,
  value: string,
  darkMode: boolean
) {
  const width = 190;
  const height = 65;

  ctx.fillStyle = darkMode ? '#161b22' : '#f6f8fa';
  drawRoundedRect(ctx, x, y, width, height, 8);
  ctx.fill();

  ctx.strokeStyle = darkMode ? '#30363d' : '#d0d7de';
  ctx.lineWidth = 1;
  drawRoundedRect(ctx, x, y, width, height, 8);
  ctx.stroke();

  ctx.fillStyle = darkMode ? '#8b949e' : '#57606a';
  ctx.font = '14px sans-serif';
  ctx.fillText(label, x + 16, y + 25);

  ctx.fillStyle = darkMode ? '#58a6ff' : '#0969da';
  ctx.font = 'bold 22px sans-serif';
  ctx.fillText(value, x + 16, y + 52);
}
